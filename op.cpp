#include <iostream>
using namespace std;
int main()
{
    int a, b;
    cin >> a;
    cin >> b;
    cout << "the value of a==b is" << (a == b) << endl;
    cout << "the value of a!=b is" << (a != b) << endl;
    cout << "the value of a>b is" << (a > b) << endl;
    cout << "the value of a<b is" << (a < b) << endl;
    cout << "the value of a<=b is" << (a <= b) << endl;
    cout << "the value of a>=b is" << (a >= b) << endl;
    return 0;
}